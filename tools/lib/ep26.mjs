import { readFile } from 'node:fs/promises';
import { EP26_PAGE } from '../../src/catalog.mjs';
import { projectPath } from './project.mjs';

export async function buildEp26() {
  const begin = '// BEGIN EP26 EMBEDDED DATA';
  const end = '// END EP26 EMBEDDED DATA';
  const parts = [begin, '// Generated by node tools/sync-ep26-data.mjs; edit src/episodes/ep26/data.js / images.js.'];
  for (const [file, name] of [['data.js', 'DATA'], ['images.js', 'IMG']]) {
    const source = await readFile(projectPath(`src/episodes/ep26/${file}`), 'utf8');
    const match = source.match(new RegExp(`^\\s*export const ${name} = ([\\s\\S]*?);?\\s*$`));
    if (!match) throw new Error(`Unexpected EP26 data format: ${file}`);
    const json = JSON.stringify(JSON.parse(match[1]))
      .replace(/</g, '\\u003c').replace(/\u2028/g, '\\u2028').replace(/\u2029/g, '\\u2029');
    parts.push(`const ${name} = ${json};`);
  }
  parts.push(end);
  const html = await readFile(projectPath(EP26_PAGE), 'utf8');
  const from = html.indexOf(begin), to = html.indexOf(end, from);
  if (from < 0 || to < from) throw new Error('EP26 embedded data markers are missing');
  const newline = html.includes('\r\n') ? '\r\n' : '\n';
  return html.slice(0, from) + parts.join(newline) + html.slice(to + end.length);
}
